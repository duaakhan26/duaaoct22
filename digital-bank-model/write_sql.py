"""Write the SSMS scripts whose column order has to match the CSV files."""

from __future__ import annotations

from pathlib import Path

from model_schema import NULLABLE, TABLES


def _expr(name: str, sql_type: str) -> str:
    source = f"NULLIF(REPLACE(s.[{name}], CHAR(13), ''), '')"
    if sql_type == "int":
        return f"TRY_CONVERT(int, {source})"
    if sql_type == "bigint":
        return f"TRY_CONVERT(bigint, {source})"
    if sql_type == "bit":
        return f"TRY_CONVERT(bit, {source})"
    if sql_type == "date":
        return f"TRY_CONVERT(date, {source})"
    if sql_type == "datetime2":
        return f"TRY_CONVERT(datetime2, {source}, 120)"
    if sql_type.startswith("decimal"):
        return "TRY_CONVERT(decimal(18,2), " + source + ")"
    if sql_type.startswith("char") or sql_type.startswith("varchar"):
        return source
    raise ValueError(sql_type)


def _create_table(schema: str, table: str, typed: bool) -> str:
    lines = [f"CREATE TABLE {schema}.{table} ("]
    columns = []
    for name, sql_type in TABLES[table]:
        if typed:
            null = "NULL" if name in NULLABLE.get(table, set()) else "NOT NULL"
            columns.append(f"    [{name}] {sql_type} {null}")
        else:
            columns.append(f"    [{name}] nvarchar(120) NULL")
    lines.append(",\n".join(columns))
    lines.append(");")
    return "\n".join(lines)


def _create_script() -> str:
    drops = []
    for table in (
        "FactPayments",
        "FactApplication",
        "FactOnboardingEvents",
        "DimAccount",
        "DimCustomer",
        "DimChannel",
        "DimOnboardingStep",
        "DimFailureReason",
        "DimBank",
        "DimDate",
        "DimTime",
    ):
        drops.append(f"DROP TABLE IF EXISTS stg.{table};")
        drops.append(f"DROP TABLE IF EXISTS dbo.{table};")
    creates = []
    for table in TABLES:
        creates.append(_create_table("dbo", table, typed=True))
        creates.append("")
        creates.append(_create_table("stg", table, typed=False))
        creates.append("")
    return f"""-- Generated by write_sql.py. Re-run generate_data.py rather than editing column order.
-- SQL Server 2017 or newer. Run 00_create_database.sql first.

USE DigitalBankDW;
GO

SET NOCOUNT ON;

IF SCHEMA_ID(N'stg') IS NULL
    EXEC(N'CREATE SCHEMA stg');
GO

{chr(10).join(drops)}
GO

{chr(10).join(creates)}
"""


def _load_block(filename: str, table: str, expected: int) -> str:
    column_names = [name for name, _sql_type in TABLES[table]]
    select_list = ",\n        ".join(
        f"{_expr(name, sql_type)} AS [{name}]" for name, sql_type in TABLES[table]
    )
    column_list = ", ".join(f"[{name}]" for name in column_names)
    return f"""
TRUNCATE TABLE stg.{table};
SET @sql = N'BULK INSERT stg.{table}
    FROM ''' + @DataPath + N'{filename}''
    WITH (FIRSTROW = 2, FIELDTERMINATOR = '','', ROWTERMINATOR = ''0x0a'', TABLOCK, KEEPNULLS);';
EXEC (@sql);
SET @actual = (SELECT COUNT(*) FROM stg.{table});
IF @actual <> {expected}
BEGIN
    SET @msg = N'{filename} loaded ' + CAST(@actual AS nvarchar(20)) + N' rows, expected {expected}.';
    THROW 50002, @msg, 1;
END;
INSERT INTO dbo.{table} ({column_list})
SELECT
        {select_list}
FROM stg.{table} AS s;
IF @@ROWCOUNT <> @actual
BEGIN
    SET @msg = N'{filename} could not be converted into dbo.{table}. A blank landed in a required column or a value was not a valid type.';
    THROW 50003, @msg, 1;
END;
"""


def _load_script(manifest: list[tuple[str, str, int]]) -> str:
    blocks = [_load_block(filename, table, expected) for filename, table, expected in manifest]
    unions = "\nUNION ALL\n".join(
        f"SELECT '{table}' AS TableName, COUNT(*) AS LoadedRows FROM dbo.{table}"
        for table in TABLES
    )
    return f"""-- Generated by write_sql.py. Re-run generate_data.py after regenerating the CSVs.
-- 1. Copy the csv folder to the SQL Server machine, for example C:\\DigitalBankData\\
-- 2. Edit @DataPath below. The SQL Server service account must be able to read that folder.
-- 3. Run 00, then 01, then this script, then 03, then 04.
-- Line endings in the CSVs are LF. A trailing CR is stripped, so a CRLF copy still loads.

USE DigitalBankDW;
GO

SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @DataPath nvarchar(400) = N'C:\\DigitalBankData\\';
DECLARE @sql nvarchar(max);
DECLARE @actual int;
DECLARE @msg nvarchar(400);

IF RIGHT(@DataPath, 1) <> N'\\'
    SET @DataPath += N'\\';

IF EXISTS (SELECT 1 FROM dbo.DimCustomer)
    THROW 50001, N'Tables are not empty. Run 01_create_tables.sql before loading again.', 1;
{''.join(blocks)}
{unions}
ORDER BY TableName;
"""


def write_sql_scripts(sql_dir: Path, manifest: list[tuple[str, str, int]]) -> None:
    sql_dir.mkdir(parents=True, exist_ok=True)
    (sql_dir / "01_create_tables.sql").write_text(_create_script(), encoding="utf-8", newline="\n")
    (sql_dir / "02_load_data.sql").write_text(_load_script(manifest), encoding="utf-8", newline="\n")
